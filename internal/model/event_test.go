package model

import (
	"bufio"
	"bytes"
	"encoding/json"
	"os"
	"strings"
	"testing"
	"unicode/utf8"
)

func readNDJSON(t *testing.T, path string) [][]byte {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatalf("open %s: %v", path, err)
	}
	defer f.Close()
	var lines [][]byte
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	for sc.Scan() {
		if line := bytes.TrimSpace(sc.Bytes()); len(line) > 0 {
			lines = append(lines, append([]byte(nil), line...))
		}
	}
	return lines
}

// Every line the 0.1 SDK ever sent must decode. The fixture was captured from the unmodified SDK
// (logging handler, Flask and ASGI integrations) and contains the shapes that were silently
// dropped before: zone-less timestamps, boolean attrs, JSON-object request bodies.
func TestGoldenV01Decodes(t *testing.T) {
	lines := readNDJSON(t, "testdata/sdk_v0.1.ndjson")
	if len(lines) < 8 {
		t.Fatalf("fixture too small: %d lines", len(lines))
	}
	var sawTruncatedAttr, sawDictBody, sawCritical, sawException, sawZoneless int
	for i, line := range lines {
		var ev Event
		if err := json.Unmarshal(line, &ev); err != nil {
			t.Fatalf("line %d does not decode: %v\n%s", i+1, err, line)
		}
		ev.Normalize()
		if ev.Timestamp.IsZero() {
			t.Fatalf("line %d: zero timestamp\n%s", i+1, line)
		}
		if bytes.Contains(line, []byte(`"ts":"20`)) && !bytes.Contains(line, []byte(`Z"`)) && !bytes.Contains(line, []byte(`+00:00`)) {
			sawZoneless++
		}
		if ev.Attrs.Get("request_body_truncated") == "true" {
			sawTruncatedAttr++
		}
		if ev.HTTP != nil && len(ev.HTTP.Body) > 0 && ev.HTTP.Body[0] == '{' {
			sawDictBody++
		}
		if bytes.Contains(line, []byte(`"level":"critical"`)) {
			sawCritical++
			if ev.Level != LevelFatal {
				t.Fatalf("critical must normalize to fatal, got %q", ev.Level)
			}
		}
		if ev.Exception != nil {
			sawException++
			if len(ev.Exception.Frames) == 0 || ev.Exception.Type == "" {
				t.Fatalf("line %d: exception without frames/type", i+1)
			}
			for _, fr := range ev.Exception.Frames {
				if fr.InApp == nil {
					t.Fatalf("v0.1 frames always carry in_app; got nil on line %d", i+1)
				}
			}
		}
	}
	if sawZoneless == 0 || sawTruncatedAttr == 0 || sawDictBody == 0 || sawCritical == 0 || sawException == 0 {
		t.Fatalf("fixture lost coverage: zoneless=%d truncated=%d dictBody=%d critical=%d exception=%d",
			sawZoneless, sawTruncatedAttr, sawDictBody, sawCritical, sawException)
	}
}

// The v0.2 golden file is generated by python-sdk/tests/gen_golden.py; it exercises the new
// optional fields end to end.
func TestGoldenV02Decodes(t *testing.T) {
	lines := readNDJSON(t, "testdata/sdk_v0.2.ndjson")
	if len(lines) == 0 {
		t.Fatal("empty v0.2 fixture")
	}
	var sawChain, sawVars, sawBreadcrumbs, sawHeaders, sawSkip, sawRuntime int
	for i, line := range lines {
		var ev Event
		if err := json.Unmarshal(line, &ev); err != nil {
			t.Fatalf("line %d: %v\n%s", i+1, err, line)
		}
		ev.Normalize()
		if ev.Timestamp.IsZero() || ev.EventID == "" || ev.SDK == nil || ev.SDK.Version == "" {
			t.Fatalf("line %d: v0.2 lines carry ts, event_id and sdk: %s", i+1, line)
		}
		if ev.Exception != nil {
			if len(ev.Exception.Chain) > 0 {
				sawChain++
			}
			for _, fr := range ev.Exception.Frames {
				if len(fr.Vars) > 0 {
					sawVars++
				}
			}
		}
		if len(ev.Breadcrumbs) > 0 {
			sawBreadcrumbs++
		}
		if ev.HTTP != nil && len(ev.HTTP.Headers) > 0 {
			sawHeaders++
		}
		if ev.SkipIssue {
			sawSkip++
		}
		if ev.Runtime != nil && ev.Runtime.Version != "" {
			sawRuntime++
		}
	}
	if sawChain == 0 || sawVars == 0 || sawBreadcrumbs == 0 || sawHeaders == 0 || sawSkip == 0 || sawRuntime == 0 {
		t.Fatalf("v0.2 fixture lost coverage: chain=%d vars=%d crumbs=%d headers=%d skip=%d runtime=%d",
			sawChain, sawVars, sawBreadcrumbs, sawHeaders, sawSkip, sawRuntime)
	}
}

func TestNormalizeCapsTheRequestBody(t *testing.T) {
	big := strings.Repeat("ü", MaxHTTPBodyBytes) // two bytes each
	ev := Event{HTTP: &HTTPInfo{Method: "POST", Body: JSONText(big)}}
	ev.Normalize()
	if n := len(ev.HTTP.Body); n > MaxHTTPBodyBytes || !utf8.ValidString(string(ev.HTTP.Body)) {
		t.Fatalf("body must be cut to the cap on a character boundary: %d bytes", n)
	}
	if ev.Attrs.Get(BodyTruncatedAttr) != "true" {
		t.Fatal("a cut body must be marked")
	}
	small := Event{HTTP: &HTTPInfo{Body: `{"a":1}`}}
	small.Normalize()
	if small.HTTP.Body != `{"a":1}` || small.Attrs.Get(BodyTruncatedAttr) != "" {
		t.Fatalf("small bodies are untouched: %+v", small)
	}
}
